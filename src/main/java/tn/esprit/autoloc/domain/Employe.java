package tn.esprit.autoloc.domain;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents an Employee in the AutoLoc system.
 * <p>
 * This class is a JPA entity that maps to the {@code employe} table in the database.
 * It holds information about an employee, including their name and role within the agency.
 * </p>
 *
 * @see RoleEmploye
 */
@Entity
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class Employe {

    /**
     * The unique identifier for the employee.
     * This is the primary key for the {@code employe} table.
     * The value is automatically generated by the database using an identity column.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long idEmploye;

    /**
     * The last name of the employee.
     */
    private String nom;

    /**
     * The first name of the employee.
     */
    private String prenom;

    /**
     * The role assigned to the employee (e.g., AGENT, MANAGER).
     * This is stored as a string in the database to ensure readability and independence
     * from the enum's ordinal value.
     *
     * @see RoleEmploye
     */
    @Enumerated(EnumType.STRING)
    private RoleEmploye role;
}
